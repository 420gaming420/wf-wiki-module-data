                <b>Docbunto</b> automatic documentation generator for Scribunto modules. The module is based on LuaDoc and LDoc. It produces documentation in the form of MediaWiki markup, using <code>@tag</code>-prefixed comments embedded in the source code of a Scribunto module. The taglet parser & doclet renderer Docbunto uses are also publicly exposed to other modules.
                
                Docbunto code items are introduced by a block comment (<code>--[[]]--</code>), an inline comment with three hyphens (<code>---</code>), or an inline <code>@tag</code> comment. The module can use static code analysis to infer variable names, item privacy (<code>local</code> keyword), tables (<code>{}</code> constructor) and functions (<code>function</code> keyword). MediaWiki and Markdown formatting is supported.
                
                Items are usually rendered in the order they are defined, if they are public items, or emulated classes extending the Lua primitives. There are many customisation options available to change Docbunto behaviour. 
                
