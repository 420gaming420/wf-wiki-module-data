                <b>Unindent</b> resets the indentation level of mulitline strings. It is useful for multiline strings inside functions and large tables. This module serves as a utility function for string parsing, [[Global Lua Modules/Testharness|Testharness]] test suites, [[Global Lua Modules/I18n|I18n]] datastores.
                
                Lua supports multiline strings in the format <code>[[\n...\n]]</code>. In general, Lua does not outdent indented multiline strings out of the box. Though Lua supports variable indentation in multiline strings, custom logic is necessary to reset the string's indentation. This module adopts a flexible approach based on string scanning.
                
                Unlike Penlight's <code>pl.text.dedent</code> behaviour where every line has the indentation of the first line removed, the line prefixed with the least non-tab whitespace is reset to zero indentation. Thus, the opening line of the string may retain some indentation <i>if</i> there are lines of less indentation terminating the string. 
                
