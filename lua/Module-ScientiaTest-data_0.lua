The '''Eidolon Teralyst''' is a gigantic spectral [[Sentient]] [[Eidolon]] creature that can be found aimlessly roaming around the [[Plains of Eidolon]] at night, acting as one of the [[Grand Boss]]es of the [[landscape]]. This is the first of the 3-night bosses of [[Plains of Eidolon]], followed by [[Eidolon Gantulyst]] and then [[Eidolon Hydrolyst]].

The Eidolons are remnants of a massive Sentient that was defeated in a battle against the [[Tenno]] during the Old War, whose remains now wander the plains perpetually searching for their lost components. These fragments are, however, still formidable creatures armed with powerful attacks and near-impenetrable defenses, and are hostile to both [[Tenno]] and [[Grineer]] alike.

It is important to note players that have not unlocked [[Transference]] from [[The War Within]] won't have any means to properly fight the {{PAGENAME},.

