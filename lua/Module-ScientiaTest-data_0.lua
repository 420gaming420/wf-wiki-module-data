==Weekly Mission==
After the completion of [[Stolen Dreams]] quest, the player will be able to run a weekly '''Ayatan Treasure Hunt''' with Maroo. This mission works similar to the occasional, parkour-oriented challenge rooms found in either [[Orokin Void]] or [[Orokin Derelict]]'s treasure room. Only this time, completing said treasure hunt is the primary objective of the mission.

The reward for completing the challenge room (and in extension the mission) is an [[Ayatan Sculpture]] that alternates each week, following a pre-determined sequence (which doesn't include Anasa and Zambuka). The mission can be completed once per week, resetting every Monday.

These treasure runs are a good deal easier if you have completed [[The War Within]], so you can use the [[Void Dash]] of your [[Operator]].

==Trivia==
*In the [[Codex]], Maroo's classified faction is none. This makes the first codex entry in the game under the enemies section to have no faction.
*Apart from the Lotus, Maroo is the first character to use the new speech animations rather than the "jaw wagging" mechanism that other characters had at the time.
*Maroo's helmet design has a striking resemblance to those worn by Steel Meridian operatives.
*When Maroo is downed by the Tenno during the [[Europa]] mission, Maroo will shoot at the Tenno from [[bleedout]] with a {{WeaponLex},, unlike regular [[Capturecapture targets]].
**This makes Maroo one of the three NPC's in game to be able to go into the "Downed" state, the others being [[Syndicate]] [[Operative]]s and [[Specter (Tenno)Specters]].
*She was the first character in the game that wears cosmetic armor available to players, in this case a single left Edo shoulder plate, with custom black colors, Edo knee plates worn on her thighs, and a Dendra leg guard on her right shin. Surprisingly, her bazaar model wears no cosmetics.
*Maroo is voiced by [https://www.voices.com/actors/Satauna#bio Satauna Howery].

