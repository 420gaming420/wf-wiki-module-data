<section begin=intro />
'''[[Corpus]] Techs''' are large crewmen in red suits and light orange visors wielding the Corpus-produced {{WeaponSupra},. They have a dangerously powerful burst fire which is only amplified with their high [[fire rate]] and short spin-up. They don't particularly have a lot of health compared to other heavy enemies, despite having over twice the health of a standard crewman at the same level. On the other hand, they will deploy [[Shield Osprey]]s to protect themselves and their fellow Corpus once their health is lowered enough, and can do so with a short cooldown time.

<section end=intro />
They will often break out of stunning effects to deploy Ospreys instantly unless they are killed with haste.

Even though they seem to have an armor helmet like other Corpus, the Tech's helmet doesn't seem to have any armor protection, therefore headshots make for a quick and simple solution. 

==Tactics==
*Corpus Tech tactics are similar to those of Grineer [[Heavy Gunner]]s, meaning these units won't find cover like the regular Corpus Crewmen. Instead, they attack continuously as long as their targets are in range.
*Techs also do not suffer from the low accuracy found in the Tenno's reverse-engineered Supra, allowing them to accurately gun down players from a distance. Even while the gun is fully spooled.
*Do not get caught in the open by a Tech with his gun fully spooled up, as a single rapid burst can incapacitate or seriously injure a Warframe. Either duck in and out of cover to reset his gun's speed or engage him in close combat so that he's forced into melee combat.
*[[Shadows of the DeadShadow Techs]], like all shadows, will target enemies behind walls and under floors instead of seeking them out or waiting for them to appear. This makes Shadow Techs more of a bullet sponge than a damage dealer.
*When they appear as allies on Invasions and Infestation alerts, they can prove very helpful due to their high damage, decent health, and ability to deploy ospreys which can shield objectives and the player.

==Notes==
*A Tech's suit can be seen in the Energy Lab within the Clan Dojo.
*The Supra buff in 17 applied to Techs as well.
*After the shield gating buff, Techs deploy Shield Ospreys very quickly and while they don't link to each other their shield bonuses will scale with the Tech's level (as they add shield based on max shield), and stack with additional ospreys making the Tech very dangerous.

==Trivia==
*As of 10.4, their base experience is now 500. Previously, it was only 50.
*As of 12, their helmets have a yellow design painted on.

==Bugs==
*Deployed Shield Ospreys from techs cannot be [[Mind Control]]led, however using Mind Control on the Tech will make ''all'' spawned Ospreys from that tech friendly for the duration.
