==Behavior==
During ''[[Nightwave]]: [[Nightwave/Series_2Series 2 â€“ The Emissary]]'', the Herald, along with a [[Zealot Proselytizer]], have a chance to spawn in ''any'' non-Arena/Quest mission, and can spawn multiple times in a single mission. Unlike [[Assassin]]s they can spawn in [[Syndicate]] missions, [[Assassination]] missions, and [[LandscapeFree Roam]] missions, and are not time-gated.

They will be marked with an [[Exterminateextermination]] mark icon when in the vicinity. Despite being of the [[Infested]] faction, they are considered friendly to all normal units in the mission, including [[Corpus]], [[Grineer]], and [[Corrupted]]. With the exception of [[Invasion]] missions, Zealots will attack the faction Tenno is currently allied with.

This Zealot is armed with a {{WeaponTorid},. When attacked, it grows toxic explosive pustules, which are then released in an area of effect burst of damage.

