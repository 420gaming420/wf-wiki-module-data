*From fourth episode onwards, Zealots will spawn as a team consists of a Herald, a Proselytizers, and a [[Zealot Baptizer]], and award {{sc200}, upon defeat.
**All of the Zealots must be killed within a short amount of time, otherwise, they will be continuously revived by Baptizer's swarm.

