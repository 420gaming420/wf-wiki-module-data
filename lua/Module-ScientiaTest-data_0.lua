Before going into the details about the fight, this section assumes that the player possesses an [[Arch-gun]] installed with both [[Orokin Catalyst]] and [[Gravimag]], and has an [[Archgun Deployer]] equipped in their [[gear]], as the fight requires the use of said weapon.

Note that an Archgun Deployer accumulates cooldown the more ammo the Arch-gun is using, up to '''5''' minutes. However, [[Terra Manker]] may spawn throughout the fight which will drop a '''Heavy Ammo Pickup''' which will instantly restore all Archgun ammo, hence refreshing the gear's cooldown. {{WFProtea},'s {{ADispensary}, can prevent the deployment cooldown from occurring by refreshing the ammo while the player has the Arch-Gun equipped, but unlike the Heavy Ammo Pickup, it cannot reset the cooldown.

Alternatively, a [[Necramech Summon]] can be deployed to bring down a [[Necramech]], which can use Archguns with regenerative ammo while still allowing the player to use their Warframe's weapons.

====Phase 1====
The Profit-Taker Orb will be found wandering around three possible locations in the Vallis until it is engaged, with massive Corpus reinforcements at the ready, occasionally deploying an alert beacon to call in stronger Vallis units. A level 60 specter of [[Little Duck]] also appears in some location, assisting the Tenno.

The player must first take down her Sentient shield, which behaves the same way as seen in the Heist's third phase. Damage and swap her weakness as necessary until her shield is completely down.

Once her shield is down, her main body can only be damaged using a Gravimag-enhanced Archgun. Call down the weapon with an '''Archgun Deployer''' and shoot down her legs, and work up to her main body. The fight will transition to the next phase when her hit points are down to '''75%'''.

====Phase 2====
Profit-Taker Orb will recover and deploy '''4''' Pylons, which will turn the Orb invulnerable until all Pylons are destroyed. They are protected by a spherical barrier that nullifies gunfire, but can be physically passed through. The Pylon itself has [[Damage/ObjectObject]]-based health, meaning neither [[Critical Hit]]s nor [[Status Effect]]s will have any effect on it.

Once the Pylons are destroyed, her main body will be vulnerable to Arch-gun fire again. Like in the first phase of the fight, fire down her legs again and then damage her main body. The phase will transition to the next when her hit points are down to '''50%'''.

====Phase 3====
This phase is mostly a repeat of the first and second phase of the fight. The Orb Mother's shielding will restore itself to full upon entering the phase, requiring the players to take down its shield again with the corresponding damage type. After her shield is stripped, take down the main body with Arch-gun fire down to '''25%''' of her health. She will then deploy '''6''' Pylons around the area which must be destroyed to transition to the final phase.

====Phase 4====
As soon as the players enter the fourth phase, they will be given a timer of '''5''' minutes to complete the fight before her satellite shielding realigns and render her unkillable, thus failing the bounty. She will restore her shield for the final time to full, which must be taken down with the appropriate damage type. And then she must be damaged with more Arch-gun fire until she is defeated.

Upon defeat, the Orb will collapse to the ground and clear the bounty, yielding a sizable amount of loot: 1 [[Crisma Toroid]], 3 [[Medical Debt-Bond]]s, 2 [[Advances Debt-Bond]], and 1 [[Familial Debt-Bond]]. Retrieve the loot and vacate the vicinity as soon as possible, as the Orb will then initiate a self-destruct protocol which will '''obliterate all Tenno and the loot in question within 300 meters.'''

====Summary====
*'''Phase 1:''' Take down the Profit-Taker's shield with the corresponding damage type. Then damage its legs working up to her main body with an Arch-gun summoned down with '''Archgun Deployer'''.
*'''Phase 2:''' The Profit-Taker deploys '''4''' [[Damage/ObjectObject]]-based Pylons which must be destroyed. Then, damage its legs and main body again with an Arch-gun.
*'''Phase 3:''' The Orb Mother will restore its shield. Take the shield down, destroy the Orb's legs and damage its main body with an Arch-gun, and then destroy the '''6''' deployed Pylons she deploys afterwards.
*'''Phase 4:''' A fail timer worth '''5''' minutes will start ticking down and the Orb Mother will restore its shield. Take its shield down, destroy its legs and damage its main body with an Arch-gun until it is defeated. Retrieve the loot and escape the vicinity as soon as possible as it will self-destruct with a lethal range of '''300m''' (the loot will also be destroyed).

==Tips==
*Players can avoid staggers and knockdown in the fight by using a combination of knockdown immunity mods such as {{MSure Footed}, ({{MPrimed Sure FootedPrimed},), {{MPower Drift}, or the [[Set_Mods#Motus_Mod_SetMotus set mods]]. Alternatively, {{ASpellbind}, or {{AFire Walker}, can be infused to provide knockdown and stagger resistance.
**Both {{ASpellbind}, and {{AFire Walker}, also provide status immunity, useful to counteract the magnetic proc from Profit-Taker's EMP Slam attack.
**While {{AFire Walker}, has a higher duration than {{ASpellbind},, it is less reliable as the player has to be on the fire trail for the immunity to take effect.
*Profit-Taker's attacks deal a lot of damage, so the player is advised to build around that.
**To survive the attacks at all, most frames will require a combination of ({{MUmbral VitalityUmbral},) {{MVitality},, {{MAerodynamic},, {{MAdaptation},, ({{MUmbral FiberUmbral},) {{MSteel FiberFiber},, {{ArcaneArcane Guardian}, and/or {{ArcaneArcane Tanker},.
***Even with a tanky setup, the players should avoid the laser sweep attack at all costs, as this attack can deal 6k effective health in 50 milliseconds. Avoiding the attack is as simple as making sure that you are not directly in front of the Profit-Taker.
**If you can survive the attacks, some form of healing is still advised. {{ArcaneMagus Elevate}, and {{ArcaneMagus Repair}, are perfect tools for the job as they do not restrict the player to certain frames or weapons.
*Taking out the [[Reinforcement BeaconReinforcement Beacons]] prevents stronger mobs from showing up that could otherwise be overwhelming.
*When modding weapons for multiple elements, it is advised to mod for one dual-stat and one single-stat element, where the single-stat element corresponds with the Primed elemental mod for that weapon such as {{MPrimed Cryo Rounds}, for primaries. Doing so balances out the elemental damage and leaves a mod slot to be used to buff the overall damage, instead of investing it in an elemental mod to create a dual stat element.
*{{AEclipse}, can be infused onto any frame using the [[Helminth]] system, allowing any frame to utilize a strong damage buff against the Profit-Taker. The light levels in [[Orb Vallis]] are consistent and will generally be high enough to make Eclipse give 100% of the damage buff, with the lowest they get being 45% ([https://old.reddit.com/r/Warframe/comments/je85rh/enhanced_graphics_engine_reduces_eclipse_damage/ source]). This makes it provide 2-4 times as much damage as {{ARoar},.
*If a player is consistently facing cooldowns on their [[Arch-gun]], they should consider using {{MAmmo Chain}, as modding for max ammo will lower the cooldown.
*[[Necramech]]s can provide quick access to a player's [[Arch-gun]] which can be modded to clear multiple elements on the shield phases. Since the Necramech Arch-gun can be modded independently of the ground Arch-gun, players can still use mod setups optimized for the armor phase on their ground Arch-gun.
**The {{WeaponArquebex}, cannot deal damage against Profit-Taker during the armor phase, but can damage the shields as normal and will easily oneshot the elements that it has covered on a full build.
**It is not recommended to use the [[Necramech]]'s [[Arch-gun]] for the armor phase as you cannot make use of most buffing abilities and [[Arcane Enhancementsarcanes]].
***The exception to this is the {{WeaponVelocitus}, as it is able to consistently take out the legs and body during the armor phase with a single charged shot for each part, without need for external buffs or [[Riven Mods]].
*[[On Call Crew]] can be used to clear the mobs that spawn and even contribute a bit towards taking out Profit-Taker's shields.

==Notes==
*The Profit-Taker Orb is immune to the effects of {{MShield Disruption},, and any armor-reducing effect (e.g. {{MCorrosive Projection},, {{MShattering Impact}, and {{MSeeking Shuriken},).
*{{WeaponZenith}, in its semi-auto mode has infinite punch-through, allowing it to destroy pylons from any point as it can pierce terrain and shield bubbles (but not the Repelling Shields), while additionally having good enough stats to damage the Profit-Taker's shield.
**{{WeaponFluctus}, also has infinite punch-through, but only has a range of 54 meters in the atmosphere, whereas pylons often land 150 meters away from the player. To make the weapon a decent alternative to the Zenith, it can be paired with {{WFZephyr},'s {{MJet Stream}, augment for {{ATurbulence}, and sufficient [[Power Strength]] as this can increase the range of the projectile to from 54 meters to a comfortable 160+ meters. Unfortunately, there is a bug which makes it difficult to use in the armor phase. For this reason, it is better to use a [[Necramech]] paired with the {{WeaponVelocitus}, to clear the armor phase as explained in one of the notes below.
**{{WeaponOpticor}, ({{WeaponOpticor VandalVandal},) will also pierce the shield bubbles, but not the terrain.
*{{WeaponBattacor}, is useful, as it can be modded to deal up to 4 different elemental damage types combined from its primary fire ({{DMagnetic},) and alternate fire modes ({{DRadiation},).
*{{WeaponKuva Nukor}, can also cover 4 elemental damage types: {{DRadiation}, innate, {{DMagnetic}, from the kuva bonus and 2 modded elements.
*{{ArcaneExodia Contagion}, makes any [[Zaw]] very suitable for the fight as it has high damage, a perfect balance between the physical elements and will innately cover {{DBlast},.
**If you throw the projectile near the rear end of Profit-Taker, it may clear {{DViral}, as Viral damage is only dealt when its head is in the explosion radius and the head is coded to be near its rear.
*The {{WeaponRedeemer}, ({{WeaponRedeemerPrime},) is a popular and cheaper alternative to {{ArcaneExodia Contagion},.
*Currently, the strongest [[Arch-gun]]s for the fight are the {{WeaponMausolon}, for Warframes and the {{WeaponVelocitus}, for Necramechs. The Mausolon features the highest DPS of rifle-like Arch-guns and has the best ammo economy, meaning that {{MAmmo Chain}, is not necessary if paired with adequate builds and frame buffs. The Velocitus, when fully charged and built for consistent damage output rather than average damage output, is able to consistently one-shot the legs and body in the armor phase without external buffs or [[Riven Mods]]. This means that it can be put on a Necramech to bypass the Warframe's lengthy Arch-Gun deployment animation and clear the armor phase faster than a Warframe could.
**The {{WeaponImperator Vandal}, and {{WeaponCorvas}, are also viable choices.
*{{WFChroma},'s {{AEffigy}, and its credit doubling aura can double the {{Cc}, [[Credits]] reward when Profit Taker finally collapses, once the bounty reward has been given, as long as any players that want it are standing within Effigy's aura when the credits are given. Additionally, due to how {{AVex Armor}, works, Chroma allows the player to free one of the mod slots for their weapon (taken by mods like {{MSerration},) and put in additional elemental mod instead.
*{{WFSaryn},'s {{AToxic Lash}, provides {{DToxin}, damage to all her weapons, allowing her to cover all 4 single-stat elements using Primary, Secondary and Melee weapons only. Additionally, the augment {{MVenom Dose}, allows her to cover {{DCorrosive}, damage with all weapons.
**Infusing {{AEclipse}, allows her to deal enough damage with each element to make her viable for quick runs.
**Similar to {{WFSaryn},, {{WFVolt}, can give {{DElectricity}, to all his weapons using {{AElectric Shield},.
*Profit-Taker Orb will randomly spawn in one of three separate locations: mountain, lake, and shrooms, in order of how close they are to [[Fortuna]]. Players are advised to land behind Profit-Taker if it spawned at the lake to avoid falling into the water, which can make the fight more difficult.
*As Profit-Taker is a corpus unit, it is affected by all damage to corpus mods such as {{MBane of Corpus}, ({{MPrimed Bane of CorpusPrimed},) and {{MSmite Corpus}, ({{MPrimed Smite CorpusPrimed},).
*The {{WeaponHystrix},'s switching elemental-damage [[Secondary Fire]] mechanic does '''not''' work on the Profit-Taker Orb. This is because unless modded for, the Hystrix quills do not deal elemental damage, only status procs, which the Orb is immune to.
*The {{WeaponParacesis}, at Rank 40 can cycle the Profit-Taker's shield damage just as the Operator Amps do.
*The Profit-Taker's shield can take a fifth of its total Shield Value before automatically switching to another elemental weakness. At its default level of 60, one-fifth of the shield value is equal to ~162,645 shield points.
*As all heist phases reward the [[Gyromag Systems]], [[Atmo Systems]], and [[Repeller Systems]] with the same rarity, completing phase 2 repeatedly is the quickest way to farm these items. With proper gear and the use of an [[Archwing]] with {{MHyperion Thrusters}, to get to Enrichment Labs and back, the phase can be completed in as little as 2 minutes.
**If players additionally need {{Cc}, [[Credits]] or [[Crisma Toroid]]s for [[Vox Solaris (Syndicate)]] standing, they could instead repeatedly complete phase 4, which can reasonably be completed in under 4 minutes.

