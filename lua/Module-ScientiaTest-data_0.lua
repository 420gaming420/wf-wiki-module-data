*{{AToxic Lash}, and {{AXata's Whisper}, create and extra damage instance that can damage Profit-Taker's body during the armor phase beyond what is normally allowed. With sufficient damage, this allows two armor phases to be cleared with a single shot to the body.
*At the start of the second shield phase, Profit-Taker will regenerate its shields beyond 100%, meaning that damage dealt in the first 2 seconds is wasted effort.
*5.1 seconds after the last pylon of a pylon phase is killed, Profit-Taker will reset the damage dealt to its legs despite them already being vulnerable for that time. This effectively negates all damage dealt to the legs. If all legs are taken out before the 5.1 seconds pass, the body will becomes vulnerable which can cause both the body and the legs vulnerable at the same time.
*Hitting one body part of the Profit-Taker with a projectile will make that projectile deal 0 damage to subsequent body parts, even if the initial body part didn't take damage. {{WeaponFluctus},, for example, has a hard time hitting legs in the back despite its infinite [[Punch Through]]: hitting the legs in front will prevent the legs in the back being from being hit by the same projectile, even if the front legs have no health left.

