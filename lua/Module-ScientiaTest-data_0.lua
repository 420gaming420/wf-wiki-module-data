Eidolons' shields and health possess DR that scales depending on your weapon's DPS.<ref>[https://www.reddit.com/r/Warframe/comments/bd6gmo/the_extremely_weird_mechanics_of_operator_amp/ Reddit post]</ref> DPS is calculated by:
:<math>(\text{modded damage})\cdot(\text{modded fire rate})\cdot(\text{modded multishot})\cdot(\text{body part multipliers})</math>
Critical Hits are applied after DR is calculated. Additionally, the average DPS is calculated using Health Modifiers and is quantized.

<math>{
\text{Damage Modifier} =
\begin{cases}
0.4,\; & \text{DPS}_{Average} \leq \frac{300}{\text{Fire Rate},\\
0.1 + \frac{300}{\text{Fire Rate} \times \text{DPS}_{Average},,\; & \text{DPS}_{Average} > \frac{300}{\text{Fire Rate},
\end{cases}
}</math>

; For critical hits
<math>{
\text{Damage Modifier} =
\begin{cases}
0.8,\; & \text{DPS}_{Average} \leq \frac{150}{\text{Fire Rate},\\
0.04 + \frac{120}{\text{Fire Rate} \times \text{DPS}_{Average},,\; & \text{DPS}_{Average} > \frac{150}{\text{Fire Rate},
\end{cases}
}</math>

==Strategy==
===General===
Due to the Teralyst possessing both [[Damage/Alloy ArmorAlloy Armor]] and [[Damage/RoboticRobotic]] health, weapons with {{DRadiation}, damage will do the most damage (+75% vs Alloy Armor, +25% vs Robotic), whilst {{DPuncture}, will also be reasonably effective (+15% vs Alloy Armor, +25% vs Robotic). Avoid using  {{DSlash}, and {{DMagnetic},. {{MCorrosive Projection}, is recommended to decrease the Teralyst's armor. {{MShield Disruption}, has no effect on its shields. Bear in mind that the Teralyst is immune to all [[Status Effect]]s, except for {{DVoid},.

Weapons with a high damage to ammo ratio are recommended. Snipers and shotguns are ideal for this purpose. Explosives are ineffective on the weak points as they will ''hit'' the invulnerable body and deal no damage, unless the projectile can make a direct hit on the weak point and explode there. Shotguns that fire projectiles, such as the {{WeaponArca Plasmor},, can be ineffective, since the weapon's damage will not register if any part of the projectile misses the joint.

Use of a [[Voidrig]] has also proven quite effective if built correctly. If its standard weapon is a strong single-target Archgun like a {{WeaponVelocitus},, and if it is equipped with key mods like {{MNecramech Rage}, to help keep its {{WeaponArquebex}, fueled, this can be highly beneficial in destroying the vulnerable points of the Teralyst while its shields are disabled.

The Teralyst is immune to all debuffing effects of Warframe powers. Therefore, highly defensive and/or self/squad buffing Warframes such as {{WFRhino},'s {{AIron Skin}, & {{ARoar},, {{WFTrinity},'s {{ABlessing},, {{WFChroma},'s Cold {{AElemental Ward}, and {{AVex Armor},, {{WFVolt},'s {{AElectric Shield},, or {{WFHarrow},'s {{ACovenant}, are good choices.

{{WFXaku},'s abilities, despite dealing {{DVoid}, damage, have no effect on the Eidolon Teralyst.

Some Warframes are well-equipped to fight the {{PAGENAME}, for the utility they bring to the squad:
*{{WFChroma}, can quickly shred and even one-shot the Synovia joints by using {{AVex Armor},'s '''Fury''' buff extensively.
*{{WFTrinity},'s {{ABlessing}, will provide extra survivability to the entire squad, as well as making sure the Eidolon Lures are kept at full health.
*{{WFHarrow},'s {{ACovenant}, can be used to render the squad immune to the {{DMagnetic}, proc of the energy spike the Teralyst emits, and provide a maximum damage buff based on the massive amount of damage prevented. Duration should be normalized, so as not to interfere with Chroma's Vex Armor.
*{{WFNezha},'s {{AWarding Halo}, can be used to negate the {{DMagnetic}, proc for yourself and with the {{MSafeguard}, augment, the entire squad. 
*{{WFLimbo},'s {{ACataclysm}, can be used to render the squad immune to most of Teralyst's attack including the {{DMagnetic}, energy spike. Operators are not affected by Cataclysm and can fire through the rift while keeping their Warframes safe. Remember to decast the ability as not to interfere with the squad's weapons once the shield is down.
**{{WFLimbo},'s {{MRift Haven}, can also be used to individually {{ABanish}, allies and Eidolon Lures to heal them while providing semi-invulnerability from Eidolon attacks.
*{{WFRhino},'s {{ARoar}, ability can be used to increase the overall party DPS, given how durable the Teralyst is. Furthermore, due to the lack of CC required, a Rhino can opt to maximize their Power Strength to provide a +186% damage buff.
*{{WFVolt},'s {{AElectric Shield},, on top of their damage and crit enhancing capability, is one of the two abilities in the game (the other being [[Energy Field]]) which can enhance the [[Operator]]'s damage, making them a solid choice if the Teralyst's shield is a concern.
*{{WFOctavia},'s [[Amp (Ability)Amp]] ability can vastly increase damage dealt by weapons for the entire squad, with enough Ability Strength; however, make sure to cast the ability where attacking the Teralyst or its Synovia is the most convenient. {{AMetronome}, and its Nocturne buff also allows the squad to evade the Teralyst's seeking bullets and the Vomvalysts' attacks.
*{{WFOberon},'s {{AHallowed Ground}, can render allies standing on it immune to status, as well as provide healing with {{ARenewal},. {{MPhoenix Renewal}, can provide additional support and {{MSmite Infusion}, can provide additional Radiation damage which is very effective against the Teralyst.
*[[Unairu]]'s Unairu Wisp can increase the entire squad's [[Operator]]'s damage by 100% when Void Blasting any enemy for 12s.

During any phase of the battle, players can bring [[Eidolon Lure]]s into the battle and charge them by either letting them absorb three Vomvalysts in their spectral ethereal form, or by picking up the energy orb they drop (indicated by a blue beacon) and passing it onto the Lure. Once they are charged, they will glow blue and if brought near the Teralyst, they will prevent it from teleporting away.

===Phase 1===
The Teralyst possesses a Sentient shield which is invulnerable to all sources of [[damage]], it can only be harmed with{{DVoid}, damage which can only be utilized by the Tenno [[Operator]] (which is unlocked after finishing the War Within).

If depleted, the Eidolon's joints &mdash; '''Teralyst Synovia''' &mdash; will become vulnerable to ''all forms ''of damage, not just {{DVoid}, damage, but damage resistances still apply. Note that their shield can still regenerate after a moderate delay if not taking any damage.

If one of their Synovia joints has been destroyed, it will drop an [[Sentient CoreExceptional Sentient Core]]. The boss will then retaliate by emitting an '''Energy Spike''' &mdash; which is a massive {{DMagnetic}, pulse expanding up to 60 meters away &mdash; and then teleport away from the Tenno and recovering 75% of their shield.

*If there is at least one charged [[Eidolon Lure]] to tether them, this teleportation can be prevented and the boss will only recover 50% of its shield.
*The [[Ancient Healer]] specters can be used to prevent status effects.
*Equipping a fully ranked [[Arcane Nullifier]] allows the warframe to resist the {{DMagnetic}, procs.
*The Operators Void Mode may also be used to completely ignore the damage and procs.
*Remember to keep the [[Eidolon Vomvalyst]] count around the Teralyst to a minimum, as they can be a threat if ignored and enables the boss to regenerate their shields via the Vomvalysts.

===Phase 2===
Once two weak points have been destroyed, it will begin two new attack patterns while modifying the aggressiveness of the Vomvalysts.

* Firstly, the Teralyst will perform '''Star Fall''' &mdash; in which the Teralyst shoots into the sky causing a hailstorm of homing explosives, covering a large area around the Teralyst in multiple explosions. Staying airborne may help to avoid the radius of the explosive projectiles.
* Secondly, the Teralyst will follow it up with '''Ground Smash''' &mdash; in which the Teralyst smashes the ground sending a series of homing quakes &mdash; spread in a starburst pattern instead of circling outwards. This pattern does not change until all weak points have been destroyed.
* Finally, the [[Eidolon Vomvalyst]]s spawned around the Teralyst will launch exploding spheres instead which deals more damage.

Once three Synovia joints have been destroyed, the Teralyst will attack more frequently and aggressively, and '''Ground Stomp''' will be followed by a slower damaging blue ring. The Vomvalyst spawn rate will increase notably.

===Phase 3===
Once all four Synovia joints have been destroyed, the Teralyst will drop down and summon a school of [[Eidolon Vomvalyst]]s in their ethereal form to merge with it. Each Vomvalyst that merges with the Teralyst will heal it. The players should intercept and kill as many as possible. This phase will end automatically after approximately 30 seconds.

===Phase 4===
In this phase, the Teralyst will not regenerate its shields and can be killed entirely. Their attack pattern closely resembles the pattern of the third phase.

Once the Teralyst dies, it will drop to the ground, dropping an [[Eidolon Shard]] as well as one of the {{MPummel},, {{MFull Contact},, {{MCrash Course},, or {{MCollision Force}, mods.

If successfully defeated while tethered by at least two charged [[Eidolon Lure]]s, the Teralyst will be '''captured'''. The lures will self-destruct and yield an additional four Intact Sentient Cores, two Exceptional Sentient Cores, a Flawless Sentient Core, and a [[Brilliant Eidolon Shard]]; all of which drop from the lures and ''not'' the corpse of the Teralyst. To know that the requirement of capture is fulfilled, listen for [[OnkkoQuill Onkko]]'s comment: ''"Sentient energy contained".''

===Summary===
* '''Preparation Phase:''' Damage an [[Eidolon Lure]] and [[Hackinghack]] it to take control of it. The Lure can then be charged by either letting it absorb a nearby [[Eidolon Vomvalyst]]'s spectral form, or by picking up the energy orb they drop (indicated by a blue beacon) and passing it onto the Lure. Each lure needs the energy of three Vomvalysts to fully charge. It is recommended to have two lures under control by the end of the hunt.
* '''Phase 1:''' The {{PAGENAME},'s shield can only be damaged with {{DVoid}, damage; this can be done with the [[Operator]]'s power. The Synovia weak points will be vulnerable once its shields have been depleted.
* '''Phase 2:''' Take down Synovia; this will trigger an energy spike of 5 {{DMagnetic}, waves in a 65-meter radius and yield an Exceptional [[Sentient Core]] for each one destroyed.
** '''With no charged Lure:''' The Teralyst will teleport away, regenerating 75% of its shield.
** '''With at least 1 charged Lure:''' The Teralyst will not teleport away, regenerating only half of its shield.
* '''Phase 3:''' Once all Synovia have been destroyed, the Teralyst will call upon surrounding Vomvalysts to heal it. Destroy these with the Operator.
* '''Phase 4:''' The Teralyst's entire body will finally be vulnerable to damage. At this point, it can be defeated.
** '''With 0-1 charged Lures (Killed):''' The Teralyst will collapse to the ground, yielding only an [[Eidolon Shard]] and an [[Arcane Enhancement]].
** '''With 2 charged Lures (Capture):''' The Teralyst will be absorbed and dissolved into the ground, the Lures tethered to it explode, yielding a generous amount of [[Sentient Core]]s, an [[Eidolon Shard]], a [[Brilliant Eidolon Shard]] and an [[Arcane Enhancement]]. Certain Arcanes are rewarded ''only'' from successful Captures.
**Capturing the Teralyst is required to summon the [[Eidolon Gantulyst]], as it is the only way to obtain the Brilliant Eidolon Shard necessary for the summoning.

==Tips==
*{{MShattering Impact}, can remove the Teralyst's armor, even while it's shielded; 21 hits will remove the Teralyst's armor entirely, though doing so will also remove its weakness to {{DRadiation}, damage. It is advised to hit it only 20 times to allow for {{DRadiation}, damage to deal bonus damage to the [[Alloy Armor]] that it has.
*The Operator's Void Mode is the best way to avoid damage from all of the Teralyst's area of effect attacks, as Void Mode renders the Operator immune to all forms of damage while leaving the Warframe similarly invulnerable to attack while the Operator is out. Companions remain vulnerable, however, so using Void Dash to escape attacks and exiting Transference to teleport your Warframe as well as your vulnerable companions away might be a better solution.
*The Eidolon Lures do ''not'' take damage from the Teralyst's energy spike.
*Remember to keep the [[Eidolon Vomvalyst]] count around the Teralyst to a minimum, as they can be a threat if ignored and enables the boss to regenerate their shields via the Vomvalysts.
*It is recommended that players with [[Eidolon Lure]]s following them should not be the main source of damage in the squad, as the lures seem to frequently drift in front of the player, blocking shots and preventing the player from damaging the Teralyst.
*Throughout the fight, only one charged Eidolon Lure is required to tether the Teralyst. Therefore, a second one can be charged later into the fight, if the players so choose.
*{{WFTrinity},'s {{ABlessing}, is invaluable for healing Eidolon Lures, especially against the Teralyst's area-of-effect attacks. Her abilities are also useful in keeping Companions alive against said attacks.
**An {{AEnergy Vampire}, Trinity is not advised as [[Eidolon Vomvalyst]]s in their spectral form are unaffected by Energy Vampire, which may be a problem for groups that kill Vomvalysts as fast as possible.
**While less effective at doing so, {{WFOberon},'s {{ARenewal}, ability can provide a similar level of healing to better sustain Teralyst attacks. Additionally, Oberon can use his {{AHallowed Ground}, plus Renewal combo to cast the '''Iron Renewal''' armor buff on allies, making them more resistant to attacks.
***{{AHallowed Ground}, skill will nullify the {{DMagnetic}, Proc effect from the pulse burst, but not the damage.
*[[Amesha]]'s abilities are very useful for the fight:
**[[Benevolent Decoy]] can absorb the Star Fall and Seeking Bullets attack and turn them into healing pulses.
**[[Warding Grace]] can block the Teralyst's magnetic procs.
**[[Vengeful Rush]] can be used to render you and your allies invulnerable while they don't have a full energy pool.
***This can be used to tank the Teralyst's magnetic blasts between stages.
