==Behavior==
The''' Teralyst''' emerges from bodies of water on the Plains at the fall of night accompanied by a column of blue light marking their location. They generally walk in one direction, even if the [[Tenno]] are nearby, though their attention can be drawn to specific locations by using [[Eidolon Lure]]s found throughout the Plains at night.

The Teralyst has many different attacks and several do very high damage, but they are all telegraphed. Once acquainted, it is possible to easily avoid the most damaging attacks.
*'''Seeking Bullets:''' A sphere of light emitted from the Teralyst's back which splits into multiple homing projectiles. These are not very accurate, and are easily avoided, but will hit in an Area of Effect even if missing.
*'''Ground Stomp:''' Stomps the ground, sending out a ground shockwave that knockbacks back any Tenno in its path a great distance (100-meter radius). Can be avoided through jumping, just like the Shockwave Moa.
*'''Ground Smash:''' Smashes the ground, sending out a series of high-damaging, homing quakes to the Tenno's position. These homing quakes can stun the Tenno and are 25m high. In later stages, these waves also return to the Teralyst.
*'''Gun Swing:''' Swings its gun arm while firing it in a wide arc, each bullet creating a 2m wide explosion.
*'''Tree Swing:''' Swings its tree arm in a short arc, dealing heavy damage. Staggers.
*'''Summoning Scream:''' The Teralyst glows orange and screeches into the air. This will summon and buff Vomvalysts around it.
*'''Regenerating Scream:''' The Teraylst glows blue and screeches. This will cause surrounding Vomvalysts (that are not affected by Summoning Scream) to link to the Teralyst and begin to regenerate its shield. Additionally, this will render it invulnerable to all damage until all linked Vomvalysts are destroyed. Has a slightly longer wind-up time than Summoning Scream.
*'''Sentient Residue:''' The Teralyst will "bleed" teal blood on the ground after losing at least one of its Synovia, dealing damage over time to those standing on it. It is hard to avoid these.
*'''Star Fall:''' Fires its gun into the sky, causing a rain of explosive, slightly homing projectiles on all targets nearby. The explosives may cause knockdown. This ability can deal damage through {{WFLimbo},'s [[Rift Plane]] and {{WFFrost},'s {{ASnow Globe},. Base area-of-effect spans 200m in radius.
*'''Energy Spikes:''' The attack Teralyst uses upon the destruction of one of his joints. This will emit five pulses of high {{DMagnetic}, damage. He will repeat this three times.
**Following this attack, if there are any vomvalysts around the Eidolon, they will perform a mini energy spike dealing a moderate amount of damage over a smaller area without the magnetic status effect.
*Additionally, destroyed arm Synovias will emit '''Seeking Bullets '''that have stronger homing capabilities, and leg Synovias will shoot out arcing shots of '''Sentient Residue '''that last a shorter duration.

